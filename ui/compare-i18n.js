/** Build a `t(key, ...args)` bound to `lang` ('ko' | 'en'); unknown keys fall back to en, then the key. */
export function makeT(lang) {
  const dict = COMPARE_I18N[lang] || COMPARE_I18N.en;
  return (key, ...args) => {
    let text = dict[key] || COMPARE_I18N.en[key] || key;
    args.forEach((a, i) => { text = text.replaceAll(`{${i}}`, String(a)); });
    return text;
  };
}

/** 'ko' | 'en' from the stored preference ('auto' → navigator language). */
export function resolveLang(stored, navigatorLanguage) {
  if (stored === 'ko' || stored === 'en') return stored;
  return String(navigatorLanguage || 'en').slice(0, 2).toLowerCase() === 'ko' ? 'ko' : 'en';
}
